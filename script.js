let typingTimer = null;

let currentCharacter = 0;

let letterFinished = false;

const openedSecrets =
  new Set();


/* =========================================
   ESCRIBIR CARTA
========================================= */

function typeLetter() {

  if (
    currentCharacter <
    letter.length
  ) {

    letterText.textContent +=
      letter[currentCharacter];

    currentCharacter++;

    const current =
      letter[currentCharacter - 1];

    let delay = 17;

    if (current === "\n") {
      delay = 190;
    }

    if (
      current === "." ||
      current === "…" ||
      current === "!"
    ) {
      delay = 45;
    }

    typingTimer =
      setTimeout(
        typeLetter,
        delay
      );

  } else {

    letterFinished = true;

    skipButton.textContent =
      "♡ Carta completa";

  }
}


/* =========================================
   MOSTRAR CARTA COMPLETA
========================================= */

function showFullLetter() {

  clearTimeout(
    typingTimer
  );

  letterText.textContent =
    letter;

  currentCharacter =
    letter.length;

  letterFinished = true;

  skipButton.textContent =
    "♡ Carta completa";
}


/* =========================================
   MÚSICA
========================================= */

async function playMusic() {

  try {

    await music.play();

    musicPlayer.classList
      .remove("paused");

    musicToggle.textContent =
      "♫";

    musicToggle.setAttribute(
      "aria-label",
      "Pausar música"
    );

  } catch (error) {

    /*
      Algunos navegadores bloquean
      autoplay con sonido.

      El primer click del usuario
      sobre el sobre/botón volverá
      a intentar reproducirla.
    */

    console.log(
      "El navegador bloqueó el autoplay:",
      error
    );

  }
}


function pauseMusic() {

  music.pause();

  musicPlayer.classList
    .add("paused");

  musicToggle.textContent =
    "▶";

  musicToggle.setAttribute(
    "aria-label",
    "Reproducir música"
  );
}


/* =========================================
   ABRIR CARTA
========================================= */

function openLetter() {

  /*
    Intentamos reproducir la música
    ANTES de cambiar de pantalla.

    El clic del usuario cuenta como
    interacción válida para autoplay
    en muchos navegadores.
  */

  playMusic();

  cover.style.display =
    "none";

  letterScreen.classList
    .add("active");

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });


  /* Reiniciar carta */

  clearTimeout(
    typingTimer
  );

  letterText.textContent =
    "";

  currentCharacter =
    0;

  letterFinished =
    false;

  skipButton.textContent =
    "Mostrar toda la carta";

  typeLetter();

}


