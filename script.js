musicToggle.addEventListener(
  "click",
  async function() {

    if (music.paused) {

      await playMusic();

    } else {

      pauseMusic();

    }

  }
);


/* =========================================
   NOTAS SECRETAS
========================================= */

document
  .querySelectorAll(
    ".secret-envelope"
  )
  .forEach(
    function(button) {

      button.addEventListener(
        "click",
        function() {

          const secret =
            button.dataset.secret;

          if (!secrets[secret]) {
            return;
          }


          /*
            Reiniciamos la animación
            cada vez que abre una nota.
          */

          secretMessage
            .classList
            .remove("visible");

          void secretMessage.offsetWidth;


          secretMessage.textContent =
            secrets[secret];

          secretMessage
            .classList
            .add("visible");


          openedSecrets.add(
            secret
          );


          /*
            Cuando las dos notas
            han sido abiertas,
            aparece la firma.
          */

          if (
            openedSecrets.size === 2
          ) {

            signature.classList
              .remove("hidden");

            setTimeout(
              function() {

                signature.scrollIntoView({
                  behavior: "smooth",
                  block: "center"
                });

              },
              350
            );

          }

        }
      );

    }
  );


/* =========================================
   AUTOPLAY
========================================= */

/*
  Intento inicial.

  Si el navegador lo permite,
  empieza la música automáticamente.

  Si no lo permite, el clic para
  abrir la carta hará el segundo intento.
*/

window.addEventListener(
  "load",
  function() {

    playMusic();

  }
);


/* =========================================
   SEGURIDAD EXTRA PARA AUTOPLAY
========================================= */

/*
  Si el navegador bloqueó el primer
  intento, cualquiera de estas primeras
  interacciones puede iniciar la música.
*/

document.addEventListener(
  "pointerdown",
  function() {

    if (music.paused) {
      playMusic();
    }

  },
  {
    once: true
  }
);
